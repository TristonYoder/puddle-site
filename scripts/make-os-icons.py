#!/usr/bin/env python3
"""Regenerate _includes/os-icon.html: the app's host platform marks as inline SVG.

Puddle Jumper draws each host's OS logo with a Nerd Font glyph from its bundled
SauceCodeProNerdFontMono (see HostPlatform.swift in swift-ssh). This copies the
same glyph outlines so the site's sessions match the app exactly.

  nix shell nixpkgs#python3Packages.fonttools -c python3 scripts/make-os-icons.py \
    ../swift-ssh/Sources/Resources/Fonts/SauceCodeProNerdFontMono-Regular.ttf
"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen

# Keep in step with HostPlatform.glyph in the app.
PLATFORMS = {
    "generic": 0xF233, "linux": 0xF31A, "ubuntu": 0xF31B, "debian": 0xF306,
    "nixos": 0xF313, "arch": 0xF303, "fedora": 0xF30A, "rocky": 0xF32B,
    "alpine": 0xF300, "opensuse": 0xF314, "raspberrypi": 0xF315, "proxmox": 0xE937,
    "docker": 0xF308, "freebsd": 0xF30C, "openbsd": 0xF328, "openwrt": 0xF382,
    "macos": 0xF302, "windows": 0xE8E5,
}

font = TTFont(sys.argv[1])
cmap, glyphs = font.getBestCmap(), font.getGlyphSet()
out = ['{%- comment -%} GENERATED by scripts/make-os-icons.py from the app\'s bundled Nerd Font. Param: name (a platform key). {%- endcomment -%}',
       '{%- case include.name -%}']
for name, cp in PLATFORMS.items():
    g = glyphs[cmap[cp]]
    bp = BoundsPen(glyphs); g.draw(bp)
    x0, y0, x1, y1 = bp.bounds
    pen = SVGPathPen(glyphs, ntos=lambda v: ("%.1f" % v).rstrip("0").rstrip("."))
    g.draw(pen)
    # Square viewBox around the glyph; flip y (font units point up).
    side = max(x1 - x0, y1 - y0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    vb = "%d %d %d %d" % (cx - side / 2, -(cy + side / 2), side, side)
    out.append('{%%- when "%s" -%%}<svg class="ic os" viewBox="%s" width="20" height="20" aria-hidden="true" focusable="false"><path transform="scale(1 -1)" fill="currentColor" d="%s"/></svg>'
               % (name, vb, pen.getCommands()))
out.append('{%- else -%}{% include icon.html name="hosts" %}')
out.append('{%- endcase -%}')
open("_includes/os-icon.html", "w").write("\n".join(out) + "\n")
print("wrote", len(PLATFORMS), "icons")
